-- =====================================================================
--  STUDENT MANAGEMENT SYSTEM  -  MySQL / MariaDB database script
--  Author : B.Tech CSE Major Project
--  Engine : InnoDB (transactional, foreign keys enforced)
--  Charset: utf8mb4 (full Unicode support)
--
--  HOW TO RUN
--    mysql -u root -p < student_management.sql
--  or open this file in MySQL Workbench / phpMyAdmin and execute it.
