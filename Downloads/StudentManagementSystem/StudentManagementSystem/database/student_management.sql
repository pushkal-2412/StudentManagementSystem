DROP DATABASE IF EXISTS student_management;
CREATE DATABASE student_management
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;
USE student_management;

SET FOREIGN_KEY_CHECKS = 1;

-- ---------------------------------------------------------------------
-- 1. ADMIN  (authentication table - stores BCrypt hashes only)
-- ---------------------------------------------------------------------
CREATE TABLE admins (
    admin_id      INT AUTO_INCREMENT PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'ADMIN',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_admin_role CHECK (role IN ('ADMIN','STAFF'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 2. DEPARTMENTS
-- ---------------------------------------------------------------------
CREATE TABLE departments (
    dept_id    INT AUTO_INCREMENT PRIMARY KEY,
    dept_code  VARCHAR(10)  NOT NULL UNIQUE,
    dept_name  VARCHAR(100) NOT NULL UNIQUE,
    hod_name   VARCHAR(100) NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 3. COURSES  (each course belongs to exactly one department)
-- ---------------------------------------------------------------------
CREATE TABLE courses (
    course_id     INT AUTO_INCREMENT PRIMARY KEY,
    course_code   VARCHAR(15)  NOT NULL UNIQUE,
    course_name   VARCHAR(100) NOT NULL,
    dept_id       INT          NOT NULL,
    duration_years INT         NOT NULL DEFAULT 4,
    course_fee    DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    description   VARCHAR(500) NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_course_dept FOREIGN KEY (dept_id)
        REFERENCES departments (dept_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_course_duration CHECK (duration_years BETWEEN 1 AND 6),
    CONSTRAINT chk_course_fee CHECK (course_fee >= 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 4. STUDENTS
-- ---------------------------------------------------------------------
CREATE TABLE students (
    student_id     INT AUTO_INCREMENT PRIMARY KEY,
    student_code   VARCHAR(20)  NOT NULL UNIQUE,
    full_name      VARCHAR(100) NOT NULL,
    dob            DATE         NOT NULL,
    gender         ENUM('Male','Female','Other') NOT NULL,
    email          VARCHAR(100) NOT NULL UNIQUE,
    phone          VARCHAR(15)  NOT NULL,
    address        VARCHAR(255) NULL,
    dept_id        INT          NOT NULL,
    course_id      INT          NOT NULL,
    academic_year  VARCHAR(15)  NOT NULL,
    admission_date DATE         NOT NULL,
    semester       INT          NOT NULL DEFAULT 1,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_student_dept FOREIGN KEY (dept_id)
        REFERENCES departments (dept_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_student_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_student_semester CHECK (semester BETWEEN 1 AND 8),
    CONSTRAINT chk_student_phone CHECK (CHAR_LENGTH(phone) BETWEEN 10 AND 15)
) ENGINE=InnoDB;

CREATE INDEX idx_student_name   ON students (full_name);
CREATE INDEX idx_student_dept   ON students (dept_id);
CREATE INDEX idx_student_course ON students (course_id);

-- ---------------------------------------------------------------------
-- 5. ENROLLMENTS  (many-to-many: student <-> course)
-- ---------------------------------------------------------------------
CREATE TABLE enrollments (
    enrollment_id INT AUTO_INCREMENT PRIMARY KEY,
    student_id    INT  NOT NULL,
    course_id     INT  NOT NULL,
    enroll_date   DATE NOT NULL,
    status        ENUM('ACTIVE','COMPLETED','DROPPED') NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT fk_enr_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE,
    CONSTRAINT fk_enr_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id) ON DELETE CASCADE,
    CONSTRAINT uq_enrollment UNIQUE (student_id, course_id)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 6. ATTENDANCE  (one row per student per course per day)
-- ---------------------------------------------------------------------
CREATE TABLE attendance (
    attendance_id INT AUTO_INCREMENT PRIMARY KEY,
    student_id    INT  NOT NULL,
    course_id     INT  NOT NULL,
    att_date      DATE NOT NULL,
    status        ENUM('PRESENT','ABSENT','LATE') NOT NULL,
    marked_by     INT  NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_att_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE,
    CONSTRAINT fk_att_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id) ON DELETE CASCADE,
    CONSTRAINT fk_att_admin FOREIGN KEY (marked_by)
        REFERENCES admins (admin_id) ON DELETE SET NULL,
    CONSTRAINT uq_attendance UNIQUE (student_id, course_id, att_date)
) ENGINE=InnoDB;

CREATE INDEX idx_att_date ON attendance (att_date);

-- ---------------------------------------------------------------------
-- 7. EXAMINATIONS
-- ---------------------------------------------------------------------
CREATE TABLE examinations (
    exam_id    INT AUTO_INCREMENT PRIMARY KEY,
    exam_name  VARCHAR(100) NOT NULL,
    course_id  INT          NOT NULL,
    exam_date  DATE         NOT NULL,
    max_marks  DECIMAL(6,2) NOT NULL,
    exam_type  ENUM('INTERNAL','MIDTERM','SEMESTER','PRACTICAL') NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_exam_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id) ON DELETE CASCADE,
    CONSTRAINT uq_exam UNIQUE (exam_name, course_id),
    CONSTRAINT chk_exam_max CHECK (max_marks > 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 8. MARKS  (marks are validated at DB level as well as in Java)
-- ---------------------------------------------------------------------
CREATE TABLE marks (
    mark_id        INT AUTO_INCREMENT PRIMARY KEY,
    exam_id        INT          NOT NULL,
    student_id     INT          NOT NULL,
    marks_obtained DECIMAL(6,2) NOT NULL,
    CONSTRAINT fk_mark_exam FOREIGN KEY (exam_id)
        REFERENCES examinations (exam_id) ON DELETE CASCADE,
    CONSTRAINT fk_mark_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE,
    CONSTRAINT uq_mark UNIQUE (exam_id, student_id),
    CONSTRAINT chk_mark_positive CHECK (marks_obtained >= 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 9. FEES  (one fee account per student; balance auto-computed)
-- ---------------------------------------------------------------------
CREATE TABLE fees (
    fee_id           INT AUTO_INCREMENT PRIMARY KEY,
    student_id       INT           NOT NULL UNIQUE,
    total_fee        DECIMAL(10,2) NOT NULL,
    paid_amount      DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    remaining_amount DECIMAL(10,2) AS (total_fee - paid_amount) STORED,
    payment_status   ENUM('PAID','PENDING','PARTIALLY_PAID') NOT NULL DEFAULT 'PENDING',
    CONSTRAINT fk_fee_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE,
    CONSTRAINT chk_fee_total CHECK (total_fee >= 0),
    CONSTRAINT chk_fee_paid CHECK (paid_amount >= 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 10. FEE_PAYMENTS  (payment history / receipts)
-- ---------------------------------------------------------------------
CREATE TABLE fee_payments (
    payment_id   INT AUTO_INCREMENT PRIMARY KEY,
    fee_id       INT           NOT NULL,
    amount       DECIMAL(10,2) NOT NULL,
    payment_date DATE          NOT NULL,
    mode         ENUM('CASH','CARD','UPI','NET_BANKING','CHEQUE') NOT NULL,
    remarks      VARCHAR(200)  NULL,
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pay_fee FOREIGN KEY (fee_id)
        REFERENCES fees (fee_id) ON DELETE CASCADE,
    CONSTRAINT chk_pay_amount CHECK (amount > 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
--  TRIGGER : keep fees.paid_amount / payment_status in sync.
--  Recalculation is SUM-based, therefore idempotent (safe to fire twice).
-- ---------------------------------------------------------------------
DELIMITER $$

CREATE TRIGGER trg_fee_payment_ai AFTER INSERT ON fee_payments
FOR EACH ROW
BEGIN
    UPDATE fees
       SET paid_amount    = (SELECT COALESCE(SUM(amount),0) FROM fee_payments
                              WHERE fee_id = NEW.fee_id),
           payment_status = CASE
                WHEN (SELECT COALESCE(SUM(amount),0) FROM fee_payments
                       WHERE fee_id = NEW.fee_id) <= 0 THEN 'PENDING'
                WHEN (SELECT COALESCE(SUM(amount),0) FROM fee_payments
                       WHERE fee_id = NEW.fee_id) >= total_fee THEN 'PAID'
                ELSE 'PARTIALLY_PAID' END
     WHERE fee_id = NEW.fee_id;
END$$

CREATE TRIGGER trg_fee_payment_au AFTER UPDATE ON fee_payments
FOR EACH ROW
BEGIN
    UPDATE fees
       SET paid_amount    = (SELECT COALESCE(SUM(amount),0) FROM fee_payments
                              WHERE fee_id = NEW.fee_id),
           payment_status = CASE
                WHEN (SELECT COALESCE(SUM(amount),0) FROM fee_payments
                       WHERE fee_id = NEW.fee_id) <= 0 THEN 'PENDING'
                WHEN (SELECT COALESCE(SUM(amount),0) FROM fee_payments
                       WHERE fee_id = NEW.fee_id) >= total_fee THEN 'PAID'
